import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('Workshopprogram.html',import.meta.url),'utf8');
const scripts=[...html.matchAll(/<script(?: [^>]*)?>([\s\S]*?)<\/script>/g)];
const elements=new Map(),storage=new Map();
function el(id){if(!elements.has(id))elements.set(id,{textContent:'',value:'',innerHTML:'',disabled:false,events:{},classList:{toggle(){}},addEventListener(n,f){(this.events[n]??=[]).push(f)},focus(){}});return elements.get(id)}
el('seed').textContent=scripts[0][1];
const context=vm.createContext({document:{getElementById:el,querySelector(){return {innerHTML:'',focus(){}}}},window:{addEventListener(){}},localStorage:{getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v)},structuredClone,console,Blob,Uint8Array,atob,crypto,URL,setTimeout,alert(){}});
vm.runInContext(scripts[1][1],context);
assert.match(el('program').innerHTML,/class="card-collapsed"/);
const toggle=()=>vm.runInContext(`$('program').events.click[0]({target:{closest(){return {dataset:{action:'toggle'},closest(){return {dataset:{id:state.cards[0].id}}}}}}})`,context);
const ids=vm.runInContext('JSON.stringify(state.cards.map(c=>c.id))',context);
toggle();assert.match(el('program').innerHTML,/aria-expanded="true"/);toggle();assert.equal(vm.runInContext('expandedCards.size',context),0);assert.equal(vm.runInContext('JSON.stringify(state.cards.map(c=>c.id))',context),ids);
vm.runInContext(`state.cards[0].attachments=[{id:'test',name:'test.txt',size:5,type:'text/plain',data:'data:text/plain;base64,aGVsbG8='}];save();render()`,context);
assert.match(el('program').innerHTML,/test.txt/);assert.equal(await vm.runInContext('attachmentBlob(state.cards[0].attachments[0]).text()',context),'hello');
assert.equal(JSON.parse(storage.values().next().value).cards[0].attachments[0].name,'test.txt');
console.log('Verified: independent expand/collapse, order preserved on repeated click, attachment rendering, decoding and persistence.');
vm.runInContext(`window.prompt=()=> 'Gemensam start';$('legend').events.click[0]({target:{closest(){return {dataset:{category:'Start'}}}}})`,context);
assert.equal(vm.runInContext('state.cards[0].kind',context),'Gemensam start');
assert.match(el('program').innerHTML,/Gemensam start/);
assert.equal(JSON.parse(storage.values().next().value).cards[0].kind,'Gemensam start');
vm.runInContext(`$('undo').onclick()`,context);
assert.equal(vm.runInContext('state.cards[0].kind',context),'Start');
assert.equal(vm.runInContext('Object.hasOwn(colors,"Gemensam start")',context),false);
console.log('Verified: category rename updates cards, dropdowns and saved state; undo restores names and colors.');
const count=vm.runInContext('state.cards.length',context);
const deleteFirst=`$('program').events.click[0]({target:{closest(){return {dataset:{action:'delete'},closest(){return {dataset:{id:state.cards[0].id}}}}}}})`;
vm.runInContext('window.confirm=()=>false',context);
vm.runInContext(deleteFirst,context);
assert.equal(vm.runInContext('state.cards.length',context),count);
vm.runInContext('window.confirm=()=>true',context);
vm.runInContext(deleteFirst,context);
assert.equal(vm.runInContext('state.cards.length',context),count-1);
vm.runInContext(`$('undo').onclick()`,context);
assert.equal(vm.runInContext('state.cards.length',context),count);
console.log('Verified: cancel preserves block; confirm deletes block; undo restores block.');
